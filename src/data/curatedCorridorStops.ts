export function getCuratedStopsForBus(busCode: string): StopTarget[] | null {
  const clean = busCode.trim().toUpperCase().replace(/[^A-Z0-9]/g, "");
  if (CURATED_CORRIDOR_STOPS[clean]) return CURATED_CORRIDOR_STOPS[clean];
  for (const key of Object.keys(CURATED_CORRIDOR_STOPS)) {
    if (clean.includes(key) || key.includes(clean)) return CURATED_CORRIDOR_STOPS[key];
  }
  return null;
}
